#!/usr/bin/env node
// Generates packages/shared/src/generated/{abis,deployments}.ts from Foundry artifacts and
// contracts/deployments/<chainId>.json. Run after `forge build` and after every deployment.
import { readFileSync, writeFileSync, readdirSync, existsSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const deploymentsDir = join(root, "contracts", "deployments");
const target = join(root, "packages", "shared", "src", "generated");
mkdirSync(target, { recursive: true });

function abiOf(file, contract = file) {
  const path = join(out, `${file}.sol`, `${contract}.json`);
  if (!existsSync(path)) throw new Error(`Missing artifact ${path}. Run \`forge build\` in contracts/ first.`);
  return JSON.parse(readFileSync(path, "utf8")).abi;
}

const morphoAbi = [
  ...abiOf("IMorpho"),
  // Morpho emits its events through EventsLib (compiled with 0.8.19, so they are not part of the interface ABI).
  ...abiOf("EventsLib").filter((x) => x.type === "event"),
];

const abis = {
  rwaSafetyGuardAbi: abiOf("RWASafetyGuard"),
  morphoAbi,
  mockUsdcAbi: abiOf("MockUSDC"),
  mockRwaTokenAbi: abiOf("MockRWAToken"),
  mockRwaOracleAbi: abiOf("MockRWAOracle"),
  demoMarketFactoryAbi: abiOf("DemoMarketFactory"),
};

const header = "// AUTO-GENERATED by scripts/sync-shared.mjs — do not edit.\n";
writeFileSync(
  join(target, "abis.ts"),
  header +
    Object.entries(abis)
      .map(([name, abi]) => `export const ${name} = ${JSON.stringify(abi, null, 2)} as const;\n`)
      .join("\n"),
);

const deployments = {};
if (existsSync(deploymentsDir)) {
  for (const f of readdirSync(deploymentsDir).filter((f) => /^\d+\.json$/.test(f))) {
    const d = JSON.parse(readFileSync(join(deploymentsDir, f), "utf8"));
    deployments[d.chainId] = d;
  }
}
writeFileSync(
  join(target, "deployments.ts"),
  header +
    `import type { RawDeployment } from "../types";\n\n` +
    `export const rawDeployments: Record<number, RawDeployment> = ${JSON.stringify(deployments, null, 2)};\n`,
);

console.log(
  `sync-shared: wrote ${Object.keys(abis).length} ABIs and deployments for chain(s) [${Object.keys(deployments).join(", ")}]`,
);
